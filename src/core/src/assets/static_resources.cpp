std::int32_t findStaticMaterialIndex(const ProjectType kind, const std::string_view material) noexcept
{
    return findIndexIgnoreCase(staticMaterials(kind), material);
}

bool isStaticMaterial(const ProjectType kind, const std::string_view material) noexcept
{
    return findStaticMaterialIndex(kind, material) >= 0;
}

std::string_view staticMaterialName(const ProjectType kind, const std::int32_t index) noexcept
{
    const auto list = staticMaterials(kind);
    if (index < 0 || static_cast<std::size_t>(index) >= list.size())
    {
        return {};
    }

    return list[static_cast<std::size_t>(index)];
}

